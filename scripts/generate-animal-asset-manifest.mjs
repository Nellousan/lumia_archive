/**
 * Generates `src/data/animal-assets.json`, listing the portraits that actually
 * exist in `public/animals`.
 *
 * The dataset needs the list to tell whether an animal has artwork at all, the
 * same way `item-assets.json` answers that question for items — reading the
 * directory at runtime would tie the build to the filesystem.
 *
 * Unlike the item sprites, the portraits are not trimmed: the card crops them to
 * the head itself (a fixed band around the centre, where the artwork puts the
 * eyes), so the transparent margin is part of the composition.
 *
 * Runs automatically via the `predev` / `prebuild` npm hooks.
 *
 *   node scripts/generate-animal-asset-manifest.mjs
 */
import { readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const portraitsDir = join(projectRoot, "public", "animals");
const outputFile = join(projectRoot, "src", "data", "animal-assets.json");

const entries = await readdir(portraitsDir, { withFileTypes: true });
const files = entries
  .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith(".png"))
  .map((entry) => entry.name.replace(/\.png$/i, ""))
  .sort();

const payload = {
  $comment:
    "Generated by scripts/generate-animal-asset-manifest.mjs from public/animals. Do not edit by hand.",
  count: files.length,
  files,
};

await writeFile(outputFile, `${JSON.stringify(payload, null, 2)}\n`, "utf8");

console.log(`[assets] ${files.length} animal portraits -> src/data/animal-assets.json`);
