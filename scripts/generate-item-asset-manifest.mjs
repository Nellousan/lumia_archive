/**
 * Generates `src/data/item-assets.json`, describing the sprites that actually
 * exist in `public/items`.
 *
 * For each sprite it records:
 *  - the item id, so the dataset can tell whether an item has artwork at all;
 *  - the bounding box of the visible pixels, so the UI can crop away the
 *    transparent padding baked into the source canvases.
 *
 * Runs automatically via the `predev` / `prebuild` npm hooks.
 *
 *   node scripts/generate-item-asset-manifest.mjs
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { findVisibleBounds } from "./lib/png-alpha-bounds.mjs";

const projectRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const spritesDir = join(projectRoot, "public", "items");
const outputFile = join(projectRoot, "src", "data", "item-assets.json");

/** Ignore near-invisible pixels, and keep 2px of bleed so edges are not clipped. */
const ALPHA_THRESHOLD = 8;
const PADDING = 2;

const entries = await readdir(spritesDir, { withFileTypes: true });
const spriteFiles = entries
  .filter((entry) => entry.isFile() && entry.name.toLowerCase().endsWith(".png"))
  .map((entry) => entry.name)
  .sort();

const files = [];
/** id -> { sw, sh, x, y, w, h }; `s` = source canvas, `x/y/w/h` = visible box. */
const trim = {};
const skipped = [];

for (const fileName of spriteFiles) {
  const id = fileName.replace(/\.png$/i, "");
  files.push(id);

  try {
    const bounds = await findVisibleBounds(await readFile(join(spritesDir, fileName)), {
      threshold: ALPHA_THRESHOLD,
      padding: PADDING,
    });

    // `null` means there was no alpha channel or nothing visible: no crop then.
    if (bounds) {
      trim[id] = {
        sw: bounds.sourceWidth,
        sh: bounds.sourceHeight,
        x: bounds.x,
        y: bounds.y,
        w: bounds.width,
        h: bounds.height,
      };
    }
  } catch (error) {
    skipped.push(`${fileName}: ${error.message}`);
  }
}

const payload = {
  $comment:
    "Generated by scripts/generate-item-asset-manifest.mjs from public/items. Do not edit by hand. " +
    "trim[id] keys: sw/sh = source canvas size, x/y/w/h = bounding box of the visible pixels.",
  count: files.length,
  files,
  trim,
};

await writeFile(outputFile, `${JSON.stringify(payload, null, 2)}\n`, "utf8");

const trimmed = Object.keys(trim).length;
console.log(
  `[assets] ${files.length} item sprites -> src/data/item-assets.json ` +
    `(${trimmed} with visible-pixel bounds)`,
);

if (skipped.length > 0) {
  console.warn(`[assets] ${skipped.length} sprite(s) left untrimmed:`);
  for (const line of skipped) console.warn(`  - ${line}`);
}
